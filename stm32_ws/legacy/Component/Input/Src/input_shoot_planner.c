/* ==========================================================================
 * 公开 API
 * --------------------------------------------------------------------------
 * 公开 API 是上层可依赖的公共语言，具体构型通过宏在编译期分派。
 * ========================================================================== */
InputStatus input_shoot_planner_map(const InputShootPlannerState *state, InputShootRef *out)
{
    if ((state == NULL) || (out == NULL)) {
        return InputNull;
    }

    input_shoot_clear(out);
    out->priority = state->priority;
    out->source = InputSourcePlanner;
    out->tick_ms = state->tick_ms;

    return InputOk;
}
