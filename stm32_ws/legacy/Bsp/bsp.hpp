#ifndef PRINTK_BSP_HPP
#define PRINTK_BSP_HPP

#include "bsp.h"

/* ==========================================================================
 * C++ 零成本包装
 * --------------------------------------------------------------------------
 * hpp 只为 C BSP 接口提供命名空间内 inline 转发，不引入运行时抽象。
 * ========================================================================== */
namespace Bsp {

/** @brief 板级初始化状态码。 */
using Status = bsp_status_t;

/** @brief 板级初始化阶段。 */
using Step = bsp_step_t;

/** @brief 板级初始化结果。 */
using Result = bsp_result_t;

/* ==========================================================================
 * inline 转发接口
 * --------------------------------------------------------------------------
 * 所有便捷函数都在编译期展开到 C API，不使用虚函数、RTTI 或动态分派。
 * ========================================================================== */
/** @brief 执行板级 BSP 一键初始化。 */
inline Status init()
{
    return bsp_init();
}

/** @brief 获取最近一次板级初始化结果。 */
inline const Result &result()
{
    return *bsp_result();
}

/** @brief 判断板级状态码是否为成功。 */
inline bool ok(Status status)
{
    return status == BSP_OK;
}

} // namespace Bsp

#endif // PRINTK_BSP_HPP
