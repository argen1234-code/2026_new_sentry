#include "debug_platform.h"

#include "bsp_timebase.h"
#include "cmsis_compiler.h"
#include "stm32h7xx.h"

/* ==========================================================================
 * 依赖与私有配置
 * --------------------------------------------------------------------------
 * 本区放置组件私有宏、上下文类型和编译期构型选择，事实来源仍是 C 实现。
 * ========================================================================== */

/* ==========================================================================
 * 公开 API
 * --------------------------------------------------------------------------
 * 公开 API 是上层可依赖的公共语言，具体构型通过宏在编译期分派。
 * ========================================================================== */
DebugIrqState debug_lock(void)
{
    uint32_t primask = __get_PRIMASK();

    __disable_irq();
    return primask;
}

void debug_unlock(DebugIrqState state)
{
    if (state == 0U) {
        __enable_irq();
    }
}

uint64_t debug_time_us(void)
{
    return bsp_timebase_now_us();
}

uint32_t debug_cycles(void)
{
    return DWT->CYCCNT;
}

bool debug_in_isr(void)
{
    return (__get_IPSR() != 0U);
}
