/* ==========================================================================
 * 公开 API
 * --------------------------------------------------------------------------
 * 公开 API 是上层可依赖的公共语言，具体构型通过宏在编译期分派。
 * ========================================================================== */
DebugStatus debug_init(void)
{
    DebugStatus status;

    status = debug_probe_reset();
    if (status != DebugOk) {
        return status;
    }
    status = debug_profiler_reset();
    if (status != DebugOk) {
        return status;
    }

    return debug_log_reset();
}
